_NOISE_WORDS = {
    "варёный", "вареный", "варёная", "вареная", "варёное", "вареное",
    "жареный", "жареная", "свежий", "свежая", "свежее",
    "спелый", "спелая", "сырой", "сырая", "отварной", "отварная",
    "печёный", "печеный", "на", "воде", "молоке", "воде",
}


def _clean(s: str) -> str:
    s = s.lower().strip()
    words = [w for w in s.split() if w not in _NOISE_WORDS]
    return re.sub(r'\s+', ' ', ' '.join(words)).strip()


def lookup(name: str) -> Optional[Tuple[str, NutritionTuple]]:
    """
    Find product by name. Returns (canonical_name, (kcal, p, f, c)) or None.
    Search order: alias → exact → longest-key-in-query → query-in-key → first-word.
    """
    s = _clean(name)

    # 1. Alias
    if s in _ALIASES:
        canonical = _ALIASES[s]
        if canonical in _DB:
            return canonical, _DB[canonical]

    # 2. Exact
    if s in _DB:
        return s, _DB[s]

    # 3. Longest key contained in query
    best, best_len = None, 0
    for key in _DB:
        if key in s and len(key) > best_len:
            best, best_len = key, len(key)
    if best:
        return best, _DB[best]

    # 4. Query contained in key
    for key in _DB:
        if s in key:
            return key, _DB[key]

    # 5. First word prefix match
    first = s.split()[0] if s else ""
    for key in _DB:
        if key.startswith(first) and len(first) >= 3:
            return key, _DB[key]

    return None
